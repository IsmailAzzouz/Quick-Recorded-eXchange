//! QRX web bindings. Reuse the *same* FQ1 Rust implementation as the desktop app.
//! Only browser-specific presentation and QR scanning live in JavaScript.

#[path = "../../../src/payload.rs"]
mod payload;

use std::collections::BTreeMap;

use js_sys::Array;
use payload::{FileAssembly, FilePacket};
use qrcodegen::{QrCode, QrCodeEcc};
use wasm_bindgen::prelude::*;

const MAX_FILE_BYTES: usize = 16 * 1024 * 1024;
const MAX_PARTS: usize = 65_536;
const MAX_TRANSFERS: usize = 4;
const MAX_QR_CHUNK_BYTES: usize = 1024;

fn js_error(message: impl ToString) -> JsValue {
    JsValue::from_str(&message.to_string())
}

/// Generate wire-compatible FQ1 packet strings from an in-memory file.
#[wasm_bindgen]
pub fn packets_from_file(filename: &str, bytes: &[u8], chunk_size: usize) -> Result<Array, JsValue> {
    if bytes.len() > MAX_FILE_BYTES {
        return Err(js_error("File exceeds the 16 MiB browser MVP limit"));
    }
    if !(128..=MAX_QR_CHUNK_BYTES).contains(&chunk_size) {
        return Err(js_error("Chunk size must be between 128 and 1024 bytes"));
    }

    let packets = FilePacket::create_packets(filename, bytes, chunk_size);
    if packets.len() > MAX_PARTS {
        return Err(js_error("Too many QR frames; increase the chunk size"));
    }

    let result = Array::new();
    for packet in &packets {
        result.push(&JsValue::from_str(&packet.serialize()));
    }
    Ok(result)
}

/// White quiet zone + QR bitmap generated by the same qrcodegen codec as desktop QRX.
#[wasm_bindgen]
pub struct QrSymbol {
    size: usize,
    modules: Vec<u8>,
}

#[wasm_bindgen]
impl QrSymbol {
    #[wasm_bindgen(constructor)]
    pub fn new(text: &str, ecc: u8) -> Result<QrSymbol, JsValue> {
        let level = match ecc {
            0 => QrCodeEcc::Low,
            1 => QrCodeEcc::Medium,
            2 => QrCodeEcc::Quartile,
            3 => QrCodeEcc::High,
            _ => return Err(js_error("Unsupported QR error correction level")),
        };
        let qr = QrCode::encode_text(text, level)
            .map_err(|err| js_error(format!("QR capacity exceeded: {err:?}")))?;
        let size = usize::try_from(qr.size()).map_err(js_error)? + 8;
        let mut modules = vec![0; size * size];
        for y in 4..size - 4 {
            for x in 4..size - 4 {
                if qr.get_module((x - 4) as i32, (y - 4) as i32) {
                    modules[y * size + x] = 1;
                }
            }
        }
        Ok(Self { size, modules })
    }

    #[wasm_bindgen(getter)]
    pub fn size(&self) -> usize {
        self.size
    }

    /// Row-major modules (0 white, 1 black).
    pub fn modules(&self) -> Vec<u8> {
        self.modules.clone()
    }
}

/// A bounded in-memory FQ1 reassembler, shared across camera/video frame scans.
#[wasm_bindgen]
#[derive(Default)]
pub struct QrxReceiver {
    keys: Vec<String>,
    assemblies: BTreeMap<String, FileAssembly>,
    received_bytes: BTreeMap<String, usize>,
}

#[wasm_bindgen]
impl QrxReceiver {
    #[wasm_bindgen(constructor)]
    pub fn new() -> QrxReceiver {
        Self::default()
    }

    /// Returns true for a newly accepted packet; false for non-FQ1 or duplicates.
    pub fn ingest(&mut self, text: &str) -> Result<bool, JsValue> {
        if !text.starts_with("FQ1|") {
            return Ok(false);
        }
        let packet = FilePacket::parse(text).map_err(js_error)?;
        if packet.parts > MAX_PARTS || packet.data.len() > MAX_QR_CHUNK_BYTES {
            return Err(js_error("FQ1 packet exceeds browser resource limits"));
        }

        let key = format!("{}:{}", packet.filename, packet.sha256);
        if !self.assemblies.contains_key(&key) {
            if self.keys.len() == MAX_TRANSFERS {
                return Err(js_error("At most four transfers can be buffered"));
            }
            self.keys.push(key.clone());
            self.assemblies
                .insert(key.clone(), FileAssembly::new(&packet));
            self.received_bytes.insert(key.clone(), 0);
        }

        let previous_size = self.received_bytes[&key];
        if previous_size.saturating_add(packet.data.len()) > MAX_FILE_BYTES {
            return Err(js_error("Transfer exceeds the 16 MiB browser MVP limit"));
        }
        let size = packet.data.len();
        let accepted = self
            .assemblies
            .get_mut(&key)
            .expect("assembly inserted above")
            .insert(packet);
        if accepted {
            *self.received_bytes.get_mut(&key).expect("size entry exists") += size;
        }
        Ok(accepted)
    }

    pub fn file_count(&self) -> usize {
        self.keys.len()
    }

    pub fn filename(&self, index: usize) -> String {
        self.get(index).map_or_else(String::new, |file| file.filename.clone())
    }

    pub fn digest(&self, index: usize) -> String {
        self.get(index).map_or_else(String::new, |file| file.sha256.clone())
    }

    pub fn total_parts(&self, index: usize) -> usize {
        self.get(index).map_or(0, |file| file.parts)
    }

    pub fn received_parts(&self, index: usize) -> usize {
        self.get(index).map_or(0, FileAssembly::received_parts)
    }

    pub fn is_complete(&self, index: usize) -> bool {
        self.get(index).is_some_and(FileAssembly::is_complete)
    }

    pub fn verification_error(&self, index: usize) -> String {
        self.get(index)
            .and_then(|file| file.verification_error.clone())
            .unwrap_or_default()
    }

    /// Only returns verified, SHA-256-matching file contents.
    pub fn verified_bytes(&self, index: usize) -> Result<Vec<u8>, JsValue> {
        self.get(index)
            .and_then(|file| file.recovered.as_ref())
            .cloned()
            .ok_or_else(|| js_error("File is incomplete or failed verification"))
    }
}

impl QrxReceiver {
    fn get(&self, index: usize) -> Option<&FileAssembly> {
        self.keys.get(index).and_then(|key| self.assemblies.get(key))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn desktop_fq1_packets_reassemble_out_of_order() {
        let data = b"browser <-> desktop protocol compatibility";
        let packets = FilePacket::create_packets("interop.bin", data, 128);
        let mut assembly = FileAssembly::new(&packets[0]);
        for packet in packets.into_iter().rev() {
            let decoded = FilePacket::parse(&packet.serialize()).unwrap();
            assert!(assembly.insert(decoded));
        }
        assert_eq!(assembly.recovered.as_deref(), Some(data.as_slice()));
    }

    #[test]
    fn corrupted_packets_do_not_verify() {
        let mut packets = FilePacket::create_packets("test.bin", b"correct", 128);
        packets[0].data[0] ^= 1;
        let mut assembly = FileAssembly::new(&packets[0]);
        assert!(assembly.insert(packets.remove(0)));
        assert!(!assembly.is_complete());
        assert!(assembly.verification_error.is_some());
    }
}
